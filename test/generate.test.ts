import { afterEach, describe, expect, test } from "bun:test";
import { mkdir, mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { applyPlan } from "../src/apply";
import { buildPlan, renderAgent } from "../src/generate";
import { parseJsonc } from "../src/jsonc";
import { MARKER, type AgentSpec } from "../src/types";

const dirs: string[] = [];

async function project(files: Record<string, string> = {}): Promise<string> {
  await mkdir("/tmp/opencode", { recursive: true });
  const root = await mkdtemp(join("/tmp/opencode", "ab-plan-"));
  dirs.push(root);
  for (const [name, content] of Object.entries(files)) {
    const path = join(root, name);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content, "utf8");
  }
  return root;
}

async function exists(path: string): Promise<boolean> {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

afterEach(async () => {
  await Promise.all(dirs.splice(0).map((dir) => rm(dir, { recursive: true, force: true })));
});

const spec: AgentSpec = {
  name: "reviewer",
  description: "Reviews changes",
  mode: "subagent",
  job: "review changes.",
  do: ["read the diff"],
  doNot: ["you do not edit", "you do not run commands"],
  verify: ["name a file and line"],
  permissions: [{ action: "edit", resource: "*", effect: "deny" }],
};

describe("renderAgent", () => {
  test("writes valid frontmatter, a marker, anti-jobs, and verify steps", () => {
    const text = renderAgent(spec);
    expect(text.startsWith("---\n")).toBe(true);
    expect(text).toContain('resource: "*"');
    expect(text).toContain(MARKER);
    expect(text).toContain("## you do not");
    expect(text).toContain("## verify");
    expect(text).toContain("one job: review changes.");
  });
});

describe("buildPlan", () => {
  test("merges existing config, preserves settings, and adds agents and AGENTS.md", async () => {
    const root = await project({
      "package.json": JSON.stringify({
        name: "demo",
        scripts: { test: "vitest", typecheck: "tsc --noEmit" },
        devDependencies: { typescript: "^5.0.0", vitest: "^2.0.0" },
      }),
      "tsconfig.json": "{}",
      "opencode.json": JSON.stringify({ model: "anthropic/claude-sonnet-5-5", permissions: [] }),
    });

    const plan = await buildPlan(root, { breadth: "standard", posture: "balanced" });
    const config = plan.files.find((file) => file.kind === "config");
    expect(config?.path).toBe("opencode.json");
    const parsed = parseJsonc(config!.content) as Record<string, unknown>;
    expect(parsed.model).toBe("anthropic/claude-sonnet-5-5");
    expect(parsed.$schema).toBe("https://opencode.ai/config.json");
    expect(parsed.instructions).toEqual(["AGENTS.md"]);
    expect(parsed.permissions).toContainEqual({ action: "shell", resource: "sudo *", effect: "deny" });

    const agentFiles = plan.files.filter((file) => file.kind === "agent").map((file) => file.path);
    expect(agentFiles).toContain(".opencode/agents/verifier.md");
    expect(agentFiles).toContain(".opencode/agents/reviewer.md");

    const instructions = plan.files.find((file) => file.kind === "instructions");
    expect(instructions?.content).toContain("## commands");
    expect(instructions?.content).toContain("typecheck: `npm run typecheck`");
  });

  test("refuses to overwrite an agent it did not generate", async () => {
    const root = await project({
      "package.json": JSON.stringify({ name: "demo" }),
      ".opencode/agents/reviewer.md": "---\ndescription: hand written\n---\nkeep me\n",
    });

    const plan = await buildPlan(root, { breadth: "lean" });
    expect(plan.files.some((file) => file.path === ".opencode/agents/reviewer.md")).toBe(false);
    expect(plan.skipped).toContainEqual({
      path: ".opencode/agents/reviewer.md",
      reason: "existing agent was not generated by this plugin; pass force=true to overwrite",
    });
  });

  test("regenerates agent files that carry the legacy generated marker", async () => {
    const root = await project({
      "package.json": JSON.stringify({ name: "demo" }),
      ".opencode/agents/reviewer.md":
        "---\ndescription: old\n---\n\n<!-- generated by opencode-agent-builder -->\n",
    });

    const plan = await buildPlan(root, { breadth: "lean" });
    const reviewer = plan.files.find((file) => file.path === ".opencode/agents/reviewer.md");
    expect(reviewer).toBeDefined();
    expect(reviewer?.content).toContain("<!-- generated by opencode-tailor -->");
  });

  test("does not clobber an existing AGENTS.md", async () => {
    const root = await project({
      "package.json": JSON.stringify({ name: "demo" }),
      "AGENTS.md": "# hand written\n",
    });
    const plan = await buildPlan(root, { breadth: "lean" });
    expect(plan.files.some((file) => file.kind === "instructions")).toBe(false);
    expect(plan.skipped.some((entry) => entry.path === "AGENTS.md")).toBe(true);
  });
});

describe("applyPlan", () => {
  test("dry run writes nothing; real run writes and verifies; second run is a no-op", async () => {
    const root = await project({
      "package.json": JSON.stringify({
        name: "demo",
        scripts: { test: "vitest", typecheck: "tsc --noEmit", lint: "eslint ." },
        devDependencies: { typescript: "^5.0.0", vitest: "^2.0.0", eslint: "^9.0.0" },
      }),
      "tsconfig.json": "{}",
    });

    const plan = await buildPlan(root, { breadth: "standard", posture: "balanced" });
    const dry = await applyPlan(plan, { dryRun: true });
    expect(dry.written.length).toBeGreaterThan(0);
    expect(await exists(join(root, ".opencode/agents/verifier.md"))).toBe(false);

    const real = await applyPlan(plan);
    expect(real.written).toContain(".opencode/agents/verifier.md");
    expect(real.written).toContain("AGENTS.md");
    expect(real.checks.every((check) => check.ok)).toBe(true);

    const verifier = await readFile(join(root, ".opencode/agents/verifier.md"), "utf8");
    expect(verifier).toContain(MARKER);
    expect(verifier).toContain("## you do not");

    const again = await applyPlan(await buildPlan(root, { breadth: "standard", posture: "balanced" }));
    expect(again.written).toEqual([]);
    expect(again.unchanged.length).toBeGreaterThan(0);
  });
});
