import { basename, join, resolve } from "node:path";
import { Plugin, Skill } from "@opencode/plugin";
import { applyPlan } from "./apply";
import { profileProject } from "./detect";
import { buildPlan } from "./generate";
import { RUBRIC } from "./rubric";
import type { Breadth, BuilderPreferences, CheckResult, Plan, Posture } from "./types";

interface PathInput {
  path?: string;
}

interface PlanInput extends PathInput {
  posture?: Posture;
  breadth?: Breadth;
  agents?: string[];
  model?: string;
  writeInstructions?: boolean;
  force?: boolean;
}

interface ApplyInput extends PlanInput {
  dryRun?: boolean;
}

const pathSchema = {
  type: "object",
  properties: {
    path: {
      type: "string",
      description: "Project directory. Defaults to the current OpenCode location.",
    },
  },
  additionalProperties: false,
} as const;

const preferenceProperties = {
  path: {
    type: "string",
    description: "Project directory. Defaults to the current OpenCode location.",
  },
  posture: {
    type: "string",
    enum: ["cautious", "balanced", "fast"],
    description: "Safety posture for global permission rules.",
  },
  breadth: {
    type: "string",
    enum: ["lean", "standard", "full"],
    description: "How many agents to generate: lean=2, standard=4ish, full=stack extras.",
  },
  agents: {
    type: "array",
    items: { type: "string" },
    description:
      "Explicit agent names, overriding breadth. Known: verifier, reviewer, test-writer, implementer, docs, migrations, security.",
  },
  model: {
    type: "string",
    description: "Optional provider/model (with optional #variant) assigned to generated agents.",
  },
  writeInstructions: {
    type: "boolean",
    description: "Write AGENTS.md when it is missing. Defaults to true only when absent.",
  },
  force: {
    type: "boolean",
    description: "Overwrite agent files not generated by this plugin, and AGENTS.md.",
  },
} as const;

const planSchema = {
  type: "object",
  properties: preferenceProperties,
  additionalProperties: false,
} as const;

const applySchema = {
  type: "object",
  properties: {
    ...preferenceProperties,
    dryRun: {
      type: "boolean",
      description: "Report what would change without writing files.",
    },
  },
  additionalProperties: false,
} as const;

function resolveRoot(input: PathInput, fallback: string): string {
  return input.path ? resolve(fallback, input.path) : fallback;
}

function preferencesFrom(input: PlanInput): BuilderPreferences {
  const preferences: BuilderPreferences = {};
  if (input.posture) preferences.posture = input.posture;
  if (input.breadth) preferences.breadth = input.breadth;
  if (Array.isArray(input.agents) && input.agents.length > 0) preferences.agents = input.agents;
  if (typeof input.model === "string" && input.model.trim()) preferences.model = input.model.trim();
  if (typeof input.writeInstructions === "boolean") preferences.writeInstructions = input.writeInstructions;
  return preferences;
}

function summarizePlan(plan: Plan) {
  return {
    root: plan.root,
    profile: {
      name: plan.profile.name,
      kinds: plan.profile.kinds,
      languages: plan.profile.languages,
      frameworks: plan.profile.frameworks,
      packageManager: plan.profile.packageManager,
      commands: plan.profile.commands,
      monorepo: plan.profile.monorepo,
      workspaces: plan.profile.workspaces,
      existing: plan.profile.existing,
      signals: plan.profile.signals,
    },
    preferences: plan.preferences,
    agents: plan.agents.map((agent) => ({
      name: agent.name,
      mode: agent.mode,
      description: agent.description,
      job: agent.job,
      doNot: agent.doNot,
      verify: agent.verify,
      permissions: agent.permissions,
      model: agent.model,
    })),
    files: plan.files.map((file) => ({ path: file.path, kind: file.kind })),
    skipped: plan.skipped,
    warnings: plan.warnings,
  };
}

interface AgentRuntime {
  reload: () => Promise<void>;
  list: () => Promise<unknown>;
}

async function runtimeAgentCheck(agentRuntime: AgentRuntime, plan: Plan): Promise<CheckResult> {
  const expected = plan.files
    .filter((file) => file.kind === "agent")
    .map((file) => basename(file.path).replace(/\.md$/, ""));
  if (expected.length === 0) {
    return { name: "runtime-agents", ok: true, detail: "no agent files planned" };
  }
  try {
    await agentRuntime.reload();
    const result = await agentRuntime.list();
    const list = Array.isArray(result)
      ? result
      : Array.isArray((result as { data?: unknown[] } | null)?.data)
        ? (result as { data: unknown[] }).data
        : Array.isArray((result as { agents?: unknown[] } | null)?.agents)
          ? (result as { agents: unknown[] }).agents
          : [];
    const ids = new Set(list.map((item) => String((item as { id?: unknown })?.id)));
    const missing = expected.filter((id) => !ids.has(id));
    return {
      name: "runtime-agents",
      ok: missing.length === 0,
      detail:
        missing.length === 0
          ? `${expected.length} generated agent(s) visible after reload`
          : `missing after reload: ${missing.join(", ")}`,
    };
  } catch (error) {
    return { name: "runtime-agents", ok: false, detail: `could not reload agents: ${String(error)}` };
  }
}

function parseFlags(input: string): { hints: string[]; note: string } {
  const hints: string[] = [];
  const words = input.split(/\s+/).filter(Boolean);
  const rest: string[] = [];
  for (const word of words) {
    if (["--yes", "--act", "--now"].includes(word)) hints.push("act now, skip intake questions (default posture=balanced, breadth=standard)");
    else if (word === "--dry-run") hints.push("dry run only, do not write files");
    else if (word === "--force") hints.push("force=true");
    else if (word === "--lean" || word === "--standard" || word === "--full") hints.push(`breadth=${word.slice(2)}`);
    else if (word === "--cautious" || word === "--balanced" || word === "--fast") hints.push(`posture=${word.slice(2)}`);
    else if (word.startsWith("--model=")) hints.push(`model=${word.slice(8)}`);
    else if (word.startsWith("--agents=")) hints.push(`agents=${word.slice(9)} (split on commas into an array)`);
    else rest.push(word);
  }
  return { hints, note: rest.join(" ") };
}

function tailorPrompt(input: string, root: string): string {
  const { hints, note } = parseFlags(input);
  const hintBlock = hints.length > 0 ? `flags from the user: ${hints.join("; ")}.` : "no flags.";
  return `you are tailor. one job: tailor this repo's opencode config and agent set.

project directory: ${root}
${hintBlock}
${note ? `user note: ${note}` : ""}

work in this order:
1. call tailor_profile with no path.
2. if the user did not say act now, ask at most three questions with the question tool: posture (cautious/balanced/fast), breadth (lean/standard/full), and any extra agents. do not ask about anything the profile already shows. if the user said act now, use posture=balanced and breadth=standard unless flags say otherwise, and do not ask.
3. call tailor_plan with the answers. show the plan in at most twelve lines: each agent name and its one job, then files, skipped, and warnings.
4. call tailor_apply. if the user asked for a dry run, stop after the report.
5. report what was written, the checks, and one command to try next.

the bar:
- one job per agent, stated in one sentence.
- every agent has explicit anti-jobs.
- every agent proves work with a command or artifact.
- no leftover tools: permissions restrict the agent to its job.
- never overwrite an agent file this plugin did not generate, or AGENTS.md, without force.
- plain lowercase prose. no filler. bias to act once the job is clear.`;
}

export default Plugin.define({
  id: "tailor",
  async setup(ctx) {
    const root = ctx.location.directory;
    const agentRuntime: AgentRuntime = {
      reload: () => ctx.agent.reload(),
      list: () => ctx.agent.list(),
    };

    const profileTool = {
      name: "profile",
      description:
        "Read a project and report its stack, commands, monorepo layout, existing OpenCode config, and agent files. Read-only.",
      input: pathSchema,
      options: { namespace: "tailor", codemode: false },
      execute: async (input: unknown) => {
        const projectRoot = resolveRoot(input as PathInput, root);
        const profile = await profileProject(projectRoot);
        return {
          content: JSON.stringify(profile, null, 2),
          metadata: { ok: true, root: projectRoot },
        };
      },
    } as const;

    const planTool = {
      name: "plan",
      description:
        "Build a project-tailored OpenCode plan: agent specs with one job, anti-jobs, verify steps and permissions, plus the files that would be written. Does not write.",
      input: planSchema,
      options: { namespace: "tailor", codemode: false },
      execute: async (input: unknown) => {
        const data = input as PlanInput;
        const projectRoot = resolveRoot(data, root);
        const plan = await buildPlan(projectRoot, preferencesFrom(data), { force: data.force === true });
        return {
          content: JSON.stringify(summarizePlan(plan), null, 2),
          metadata: { ok: true, root: projectRoot, agents: plan.agents.length, files: plan.files.length },
        };
      },
    } as const;

    const applyTool = {
      name: "apply",
      description:
        "Write the project-tailored opencode config, agent files, and AGENTS.md, then verify them. Merges existing config and refuses to overwrite files it did not generate unless force=true.",
      input: applySchema,
      options: { namespace: "tailor", codemode: false },
      execute: async (input: unknown) => {
        const data = input as ApplyInput;
        const projectRoot = resolveRoot(data, root);
        const plan = await buildPlan(projectRoot, preferencesFrom(data), { force: data.force === true });
        const report = await applyPlan(plan, { dryRun: data.dryRun === true });
        if (!report.dryRun) {
          report.checks.push(await runtimeAgentCheck(agentRuntime, plan));
        }
        return {
          content: JSON.stringify(report, null, 2),
          metadata: {
            ok: report.checks.every((check) => check.ok),
            root: projectRoot,
            written: report.written.length,
            checks: report.checks.length,
          },
        };
      },
    } as const;

    const tailorCommand = {
      name: "tailor",
      description: "Design a project-tailored opencode config and agent set.",
      execute: async (input: {
        sessionID: string;
        prompt: { text: string };
        delivery: "steer" | "queue";
      }) => {
        await ctx.session.prompt({
          sessionID: input.sessionID,
          text: tailorPrompt(input.prompt.text, root),
          delivery: input.delivery,
        });
      },
    };

    const registrations: Array<{ dispose: () => Promise<void> }> = [];

    registrations.push(
      await ctx.tool.transform((editor) => {
        editor.namespace({
          name: "tailor",
          description: "Design and write a project-tailored OpenCode config and agents.",
        });
        editor.add(profileTool);
        editor.add(planTool);
        editor.add(applyTool);
      }),
    );

    registrations.push(
      await ctx.command.transform((editor) => {
        editor.add(tailorCommand);
      }),
    );

    try {
      registrations.push(
        await ctx.skill.transform((editor) => {
          editor.add({
            id: Skill.ID.make("tailor"),
            name: Skill.Name.make("Tailor"),
            description:
              "Design project-tailored OpenCode agents with one job, explicit anti-jobs, verification, and no leftover tools.",
            path: Skill.Info.fields.path.make(join(root, ".opencode", "skills", "tailor", "SKILL.md")),
            content: RUBRIC,
          });
        }),
      );
    } catch (error) {
      console.warn(`[tailor] skill registration failed: ${String(error)}`);
    }

    return async () => {
      await Promise.allSettled(registrations.map((registration) => registration.dispose()));
    };
  },
});
