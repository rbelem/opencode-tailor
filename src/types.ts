/**
 * Shared shapes for the builder. Kept dependency-free so the planner and the
 * recipes can be unit-tested without the OpenCode runtime.
 */

export type Posture = "cautious" | "balanced" | "fast";
export type Breadth = "lean" | "standard" | "full";
export type Effect = "allow" | "ask" | "deny";
export type AgentMode = "primary" | "subagent" | "all";

export type CommandKind =
  | "install"
  | "dev"
  | "build"
  | "test"
  | "e2e"
  | "lint"
  | "typecheck"
  | "format";

export interface PermissionRule {
  action: string;
  resource: string;
  effect: Effect;
}

export interface ProjectProfile {
  root: string;
  name: string;
  /** Broad ecosystem buckets, e.g. node, python, go, rust, docker. */
  kinds: string[];
  languages: string[];
  frameworks: string[];
  packageManager?: string;
  commands: Partial<Record<CommandKind, string>>;
  /** Human-readable clues that did not become commands (e.g. "biome configured"). */
  commandHints: string[];
  monorepo: boolean;
  workspaces: string[];
  existing: {
    configs: string[];
    agents: string[];
    instructions: string[];
    skills: string[];
  };
  signals: string[];
  notes: string[];
}

export interface BuilderPreferences {
  posture?: Posture;
  breadth?: Breadth;
  /** Explicit agent names. When set, replaces breadth-based selection. */
  agents?: string[];
  /** provider/model with optional #variant, passed through to generated agents. */
  model?: string;
  /** Write AGENTS.md when it is missing. Defaults to true only when absent. */
  writeInstructions?: boolean;
}

export interface AgentSpec {
  name: string;
  description: string;
  mode: AgentMode;
  /** One sentence. This is the agent's only job. */
  job: string;
  do: string[];
  /** Explicit anti-jobs: things the agent must not do. */
  doNot: string[];
  /** Evidence the agent must produce before calling work done. */
  verify: string[];
  permissions: PermissionRule[];
  model?: string;
  color?: string;
  steps?: number;
}

export type PlannedFileKind = "agent" | "instructions" | "config";

export interface PlannedFile {
  path: string;
  content: string;
  kind: PlannedFileKind;
}

export interface SkippedFile {
  path: string;
  reason: string;
}

export interface Plan {
  root: string;
  profile: ProjectProfile;
  preferences: BuilderPreferences;
  agents: AgentSpec[];
  files: PlannedFile[];
  skipped: SkippedFile[];
  config: Record<string, unknown>;
  warnings: string[];
}

export interface ApplyReport {
  root: string;
  dryRun: boolean;
  written: string[];
  unchanged: string[];
  skipped: SkippedFile[];
  checks: CheckResult[];
  warnings: string[];
}

export interface CheckResult {
  name: string;
  ok: boolean;
  detail: string;
}

export const MARKER = "<!-- generated by opencode-tailor -->";
export const LEGACY_MARKERS = ["<!-- generated by opencode-agent-builder -->"];
